  /// فك تشفير مصفوفة bytes
  static String _decode(List<int> encrypted) {
    try {
      final decoded = <int>[];
      for (int i = 0; i < encrypted.length; i++) {
        decoded.add(encrypted[i] ^ _key[i % _key.length]);
      }
      return utf8.decode(decoded, allowMalformed: true);
    } catch (_) {
      return '';
    }
  }

  /// استخراج كل الروابط
  static List<String> getPlaylistUrls() {
    final result = <String>[];
    for (final enc in _encrypted) {
      final url = _decode(enc);
      if (url.isNotEmpty) result.add(url);
    }
    return result;
  }

